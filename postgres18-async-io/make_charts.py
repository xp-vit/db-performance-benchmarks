#!/usr/bin/env python3
"""Stdlib-only: results/raw/*.jsonl -> results/charts/cold-scans.svg + summary table (stdout).

MB/s here is recomputed as mb_read / (exec_ms/1000) from the raw fields; the mb_per_s
field written by bench/run-cold.sh truncates seconds to 0.1 s (bc scale=1) and overstates it.
"""
import glob, json, os, statistics as st

ROOT = os.path.dirname(os.path.abspath(__file__))
rows = [json.loads(l) for f in sorted(glob.glob(os.path.join(ROOT, "results/raw/*.jsonl")))
        for l in open(f) if l.strip()]
METHODS = ["sync", "worker", "io_uring"]
COLORS = {"sync": "#8a8985", "worker": "#2a78d6", "io_uring": "#eb6834"}

def recs(**kw):
    return [r for r in rows if all(r.get(k) == v for k, v in kw.items())]

def med(rs, f):
    return st.median(r[f] for r in rs)

# ---- table ----
print("| workload | eic | io_method | median exec ms | min-max ms | MB/s (recomputed) | speedup vs sync | n |")
print("|---|---|---|---|---|---|---|---|")
data = {}
for op in ["seqscan", "bitmap"]:
    for eic in [1, 16, 64]:
        base = med(recs(op=op, phase="cold", io_method="sync", eic=eic), "exec_ms")
        for m in METHODS:
            rs = recs(op=op, phase="cold", io_method=m, eic=eic)
            ms = med(rs, "exec_ms"); data[(op, eic, m)] = ms
            mbs = st.median(r["mb_read"] / (r["exec_ms"] / 1000) for r in rs)
            vals = [r["exec_ms"] for r in rs]
            print(f"| cold {op} | {eic} | {m} | {ms:,.0f} | {min(vals):,.0f}-{max(vals):,.0f} | {mbs:,.0f} | {base/ms:.2f}x | {len(rs)} |")

# ---- chart: two panels, grouped bars, median cold exec time ----
W, H, PAD_L, PAD_T, PANEL_H, GAP = 760, 600, 64, 96, 170, 84
ymax = 18000
svg = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" font-family="system-ui,sans-serif" font-size="12">',
       f'<rect width="{W}" height="{H}" fill="#fcfcfb"/>',
       '<text x="20" y="28" font-size="16" font-weight="600" fill="#1f1f1e">PostgreSQL 18.4 cold scans, 30M rows: median execution time (lower is better)</text>',
       '<text x="20" y="48" fill="#5f5e5a">Median of 3 runs; shared_buffers and OS page cache dropped before each run. Label = speedup vs sync.</text>',
       '<text x="20" y="64" fill="#5f5e5a">One rig: Ryzen 9 7950X3D, Samsung 990 PRO NVMe (local, not EBS), ext4, kernel 6.12, Docker.</text>']
lx = W - 250
for i, m in enumerate(METHODS):
    svg.append(f'<rect x="{lx + i*80}" y="78" width="10" height="10" rx="2" fill="{COLORS[m]}"/>'
               f'<text x="{lx + i*80 + 14}" y="87" fill="#3d3d3a">{m}</text>')
for p, op in enumerate(["seqscan", "bitmap"]):
    top = PAD_T + 20 + p * (PANEL_H + GAP); base_y = top + PANEL_H
    svg.append(f'<text x="20" y="{top-8}" font-weight="600" fill="#1f1f1e">Cold {"sequential scan" if op=="seqscan" else "bitmap heap scan (~5% scattered rows)"}</text>')
    for t in range(0, ymax + 1, 4000):
        y = base_y - t / ymax * PANEL_H
        svg.append(f'<line x1="{PAD_L}" x2="{W-20}" y1="{y:.1f}" y2="{y:.1f}" stroke="#e6e5e0" stroke-width="1"/>'
                   f'<text x="{PAD_L-6}" y="{y+4:.1f}" text-anchor="end" fill="#6b6a65">{t/1000:.0f} s</text>')
    gw = (W - 20 - PAD_L) / 3
    for g, eic in enumerate([1, 16, 64]):
        gx = PAD_L + g * gw
        svg.append(f'<text x="{gx+gw/2:.1f}" y="{base_y+18}" text-anchor="middle" fill="#3d3d3a">effective_io_concurrency = {eic}</text>')
        bw = 36; x0 = gx + gw/2 - (3*bw + 2*2)/2
        sync_ms = data[(op, eic, "sync")]
        for i, m in enumerate(METHODS):
            ms = data[(op, eic, m)]; h = ms / ymax * PANEL_H; x = x0 + i*(bw+2); y = base_y - h
            svg.append(f'<path d="M{x:.1f},{base_y} V{y+4:.1f} q0,-4 4,-4 H{x+bw-4:.1f} q4,0 4,4 V{base_y} Z" fill="{COLORS[m]}">'
                       f'<title>{op} eic={eic} {m}: {ms:,.0f} ms ({sync_ms/ms:.2f}x vs sync)</title></path>')
            svg.append(f'<text x="{x+bw/2:.1f}" y="{y-4:.1f}" text-anchor="middle" font-size="11" fill="#3d3d3a">{sync_ms/ms:.2f}x</text>')
        svg.append(f'<line x1="{gx+8:.1f}" x2="{gx+gw-8:.1f}" y1="{base_y}" y2="{base_y}" stroke="#9a9993"/>')
svg.append('<text x="20" y="590" font-size="11" fill="#6b6a65">Source: postgres18-async-io/results/raw/cold-20260719-005125.jsonl (generated by make_charts.py)</text></svg>')
out = os.path.join(ROOT, "results/charts/cold-scans.svg")
open(out, "w").write("\n".join(svg) + "\n")
print(f"\nwrote {out}")
